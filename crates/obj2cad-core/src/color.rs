/// Linear light → the nearest 8-bit sRGB value.
pub fn to_srgb(linear: f64) -> u8 {
    THRESHOLDS.partition_point(|&t| t <= linear) as u8
}

/// A weighted mix of colors in linear light.
#[derive(Debug, Clone, Copy, Default)]
pub struct Mix {
    sum: [f64; 3],
    weight: f64,
}

impl Mix {
    /// Add a linear color with a weight.
    pub fn add_linear(&mut self, rgb: [f64; 3], w: f64) {
        for (s, c) in self.sum.iter_mut().zip(rgb) {
            *s += c * w;
        }
        self.weight += w;
    }

    /// Add an 8-bit sRGB color with a weight.
    pub fn add(&mut self, rgb: [u8; 3], w: f64) {
        self.add_linear(rgb.map(|c| TO_LINEAR[c as usize]), w);
    }

    /// The mixed color as 8-bit sRGB (`None` if nothing was added).
    pub fn srgb(&self) -> Option<[u8; 3]> {
        (self.weight > 0.0).then(|| self.sum.map(|s| to_srgb(s / self.weight)))
    }
}

/// Colors that differ by at most this many levels in every channel may share an entity:
/// the shared color is then within about 2 levels (under 1%) of each.
pub const MERGE_RANGE: u8 = 4;

/// Reduce weighted colors to at most `max` representatives, so a model colored per face
/// becomes a few entities rather than one per face. Colors are split where the weighted
/// error is largest (so what covers most of the model is kept closest), and only colors
/// within [`MERGE_RANGE`] of each other are merged once there is room for all the rest.
/// Each representative is its colors' weighted mix. Returns the representatives and,
/// for each input color, the index of its representative.
pub fn reduce(colors: &[[u8; 3]], weights: &[f64], max: usize) -> (Vec<[u8; 3]>, Vec<u16>) {
    use std::collections::BTreeMap;
    // Distinct colors with their summed weight and count.
    let mut distinct: BTreeMap<[u8; 3], (f64, f64)> = BTreeMap::new();
    for (c, &w) in colors.iter().zip(weights) {
        let e = distinct.entry(*c).or_default();
        e.0 += if w.is_finite() && w > 0.0 { w } else { 0.0 };
        e.1 += 1.0;
    }
    let mut boxes = vec![Bin::new(distinct.into_iter().collect())];
    while boxes.len() < max.max(1) {
        let Some(i) = (0..boxes.len())
            .filter(|&i| boxes[i].splittable())
            .max_by(|&a, &b| boxes[a].error.total_cmp(&boxes[b].error).then(b.cmp(&a)))
        else {
            break;
        };
        let (left, right) = boxes.swap_remove(i).split();
        boxes.push(left);
        boxes.push(right);
    }
    boxes.sort_by_key(|b| b.entries[0].0);
    let palette: Vec<[u8; 3]> = boxes.iter().map(Bin::representative).collect();
    let mut index: BTreeMap<[u8; 3], u16> = BTreeMap::new();
    for (i, b) in boxes.iter().enumerate() {
        for (c, _) in &b.entries {
            index.insert(*c, i as u16);
        }
    }
    (palette, colors.iter().map(|c| index[c]).collect())
}

/// Channel weights for the error measure (green is seen most sharply, blue least).
const CHANNEL: [f64; 3] = [2.0, 4.0, 3.0];

/// A box of distinct colors, each with (weight, count).
struct Bin {
    entries: Vec<([u8; 3], (f64, f64))>,
    /// Weighted squared error around the box's mean.
    error: f64,
    /// Channel with the most weighted variance.
    axis: usize,
    range: u8,
}

impl Bin {
    fn new(entries: Vec<([u8; 3], (f64, f64))>) -> Bin {
        // Weight by area; boxes of only weightless faces count faces instead.
        let by_count = entries.iter().all(|e| e.1 .0 == 0.0);
        let w = |e: &([u8; 3], (f64, f64))| if by_count { e.1 .1 } else { e.1 .0 };
        let total: f64 = entries.iter().map(w).sum();
        let mut var = [0.0; 3];
        let mut range = 0u8;
        for (k, v) in var.iter_mut().enumerate() {
            let mean = entries
                .iter()
                .map(|e| w(e) * f64::from(e.0[k]))
                .sum::<f64>()
                / total;
            *v = CHANNEL[k]
                * entries
                    .iter()
                    .map(|e| {
                        let d = f64::from(e.0[k]) - mean;
                        w(e) * d * d
                    })
                    .sum::<f64>();
            let (lo, hi) = entries
                .iter()
                .fold((255u8, 0u8), |(lo, hi), e| (lo.min(e.0[k]), hi.max(e.0[k])));
            range = range.max(hi - lo);
        }
        let axis = (0..3).fold(0, |best, k| if var[k] > var[best] { k } else { best });
        Bin {
            error: var.iter().sum(),
            axis,
            range,
            entries,
        }
    }

    fn splittable(&self) -> bool {
        self.entries.len() > 1 && self.range > MERGE_RANGE
    }

    /// Split at the weighted median of the widest channel (by variance).
    fn split(mut self) -> (Bin, Bin) {
        let ch = if self.error > 0.0 { self.axis } else { 0 };
        self.entries.sort_by_key(|e| (e.0[ch], e.0));
        let by_count = self.entries.iter().all(|e| e.1 .0 == 0.0);
        let w = |e: &([u8; 3], (f64, f64))| if by_count { e.1 .1 } else { e.1 .0 };
        let total: f64 = self.entries.iter().map(w).sum();
        let (mut acc, mut cut) = (0.0, 1);
        for (j, e) in self.entries.iter().enumerate() {
            acc += w(e);
            if acc * 2.0 >= total {
                cut = j + 1;
                break;
            }
        }
        let cut = cut.clamp(1, self.entries.len() - 1);
        let right = self.entries.split_off(cut);
        (Bin::new(self.entries), Bin::new(right))
    }

    fn representative(&self) -> [u8; 3] {
        let by_count = self.entries.iter().all(|e| e.1 .0 == 0.0);
        let mut mix = Mix::default();
        for e in &self.entries {
            mix.add(e.0, if by_count { e.1 .1 } else { e.1 .0 });
        }
        mix.srgb().unwrap_or(self.entries[0].0)
    }
}

