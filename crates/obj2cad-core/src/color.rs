    #[test]
    fn keeps_every_color_when_there_is_room() {
        let colors: Vec<[u8; 3]> = (0..200u32)
            .map(|i| [(i % 256) as u8, (i * 7 % 256) as u8, 40])
            .collect();
        let w = vec![1.0; colors.len()];
        let (p, idx) = reduce(&colors, &w, 256);
        assert_eq!(
            p,
            colors
                .iter()
                .copied()
                .collect::<std::collections::BTreeSet<_>>()
                .into_iter()
                .collect::<Vec<_>>()
        );
        assert!(colors.iter().zip(&idx).all(|(c, &i)| p[i as usize] == *c));
        assert_eq!(reduce(&colors, &w, 256), (p, idx), "deterministic");
        // Shades a level or two apart share one color, close to each.
        let near = [
            [100, 100, 100],
            [101, 100, 100],
            [102, 101, 100],
            [100, 102, 101],
        ];
        let (p, idx) = reduce(&near, &[1.0; 4], 256);
        assert_eq!((p.len(), idx), (1, vec![0; 4]));
        assert!(near
            .iter()
            .all(|c| (0..3).all(|k| p[0][k].abs_diff(c[k]) <= 2)));
    }

    #[test]
    fn a_full_palette_favors_what_covers_most() {
        // A big red face and many tiny, varied faces: red keeps its exact color.
        let mut colors = vec![[200, 30, 30]];
        let mut w = vec![1000.0];
        for i in 0..100u8 {
            colors.push([i * 2, 100, 200]);
            w.push(0.01);
        }
        let (p, idx) = reduce(&colors, &w, 8);
        assert_eq!(p.len(), 8);
        assert_eq!(p[idx[0] as usize], [200, 30, 30]);
    }

    #[test]
    fn identical_and_weightless_colors() {
        let (p, idx) = reduce(&[[1, 2, 3], [1, 2, 3]], &[0.0, 0.0], 8);
        assert_eq!((p, idx), (vec![[1, 2, 3]], vec![0, 0]));
    }
